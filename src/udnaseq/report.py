def savefig(fig, out: Path, stem: str, formats=("png", "svg")):
    out.mkdir(parents=True, exist_ok=True)
    for f in formats:
        meta = {"Date": None} if f in ("svg", "pdf") else {}
        fig.savefig(out / f"{stem}.{f}", dpi=300, bbox_inches="tight", metadata=meta)
    plt.close(fig)


class Report:
    """Collect legacy-vs-new checks and render them as Markdown."""

    def __init__(self, title: str, purpose: str):
        self.title, self.purpose = title, purpose
        self.rows, self.notes = [], []

    def check(self, item, legacy, new, status, comment=""):
        fmt = lambda x: f"{x:.4g}" if isinstance(x, float) else str(x)
        self.rows.append((item, fmt(legacy), fmt(new), status, comment))

    def note(self, text):
        self.notes.append(text)

    def write(self, path: Path):
        lines = [f"# {self.title}", "", self.purpose, "",
                 f"_Generated by `run.py` on {_dt.date.today().isoformat()}._", "",
                 "## Legacy vs regenerated", "",
                 "| Item | Legacy / manuscript | Regenerated | Status | Comment |",
                 "|---|---|---|---|---|"]
        lines += [f"| {' | '.join(r)} |" for r in self.rows]
        if self.notes:
            lines += ["", "## Notes", ""] + [f"- {n}" for n in self.notes]
        Path(path).write_text("\n".join(lines) + "\n")
        print("\n".join(lines))


def status(diff, tol_exact=1e-4, tol_close=0.05):
    if diff <= tol_exact:
        return "MATCH"
    return "CLOSE" if diff <= tol_close else "DIFFERS"
